"""Japanese / English UI strings.  ``tr("key", **fmt)``."""

from __future__ import annotations

import locale
import os

_lang = "ja"


def system_language() -> str:
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        v = os.environ.get(var, "")
        if v:
            return "ja" if v.lower().startswith("ja") else "en"
    try:
        loc = locale.getlocale()[0] or ""
    except ValueError:
        loc = ""
    return "ja" if loc.lower().startswith(("ja", "japanese")) else "en"


def resolve(setting: str, system: str | None = None) -> str:
    if setting in ("ja", "en"):
        return setting
    return system or system_language()


def set_language(code: str) -> None:
    global _lang
    _lang = "en" if code == "en" else "ja"


def language() -> str:
    return _lang


def tr(key: str, **fmt) -> str:
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[0] if _lang == "ja" else pair[1]
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError, ValueError):
            return text
    return text


